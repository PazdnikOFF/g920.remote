/*
 * Пометка горячего пути.
 *
 * G920_HOT кладёт функцию в IRAM. Это не про скорость исполнения — она та
 * же, — а про **джиттер**.
 *
 * Код по умолчанию живёт во флеше и исполняется через кэш инструкций.
 * Промах кэша тянет строку в 32 байта по QSPI и стоит около микросекунды.
 * На горячем пути таких промахов легко набирается десяток, и это уже
 * вчетверо больше, чем весь наш счёт инструкций. Хуже того, промахи
 * случаются недетерминированно — ровно тогда, когда кэш вытеснили драйверы
 * Wi-Fi и USB, то есть в самый неподходящий момент. Получается не ровная
 * задержка, а рваная, а рваную человек за рулём чувствует сильнее.
 *
 * IRAM снимает этот разброс целиком: попаданий и промахов там нет.
 *
 * ⚠ IRAM мало — сотни килобайт на всё, включая обработчики прерываний
 * Wi-Fi и USB. Помечать нужно только то, что действительно исполняется на
 * каждый кадр, и только после замера. Пометить всё подряд — значит не
 * оставить места тем, кому IRAM нужнее.
 */

#ifndef G920_HOT_H
#define G920_HOT_H

#if defined(ESP_PLATFORM)
#include "esp_attr.h"
#define G920_HOT IRAM_ATTR
#else
#define G920_HOT
#endif

#endif /* G920_HOT_H */
